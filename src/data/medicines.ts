export const getMedicine = (id: string) => MEDICINES.find((m) => m.id === id);

export function searchMedicines(query: string, letter?: string, category?: string) {
  const q = query.trim().toLowerCase();
  return MEDICINES.filter((m) => {
    if (letter && !m.generic.toUpperCase().startsWith(letter)) return false;
    if (category && m.category !== category) return false;
    if (!q) return true;
    return (
      m.generic.toLowerCase().includes(q) ||
      m.brands.some((b) => b.toLowerCase().includes(q)) ||
      m.drugClass.toLowerCase().includes(q) ||
      m.category.toLowerCase().includes(q) ||
      m.indications.some((i) => i.toLowerCase().includes(q))
    );
  }).sort((a, b) => a.generic.localeCompare(b.generic));
}

